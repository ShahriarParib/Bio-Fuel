#!/usr/bin/env bash
# Runs every resilience drill against the live stack and writes docs/evidence/resilience.md.
#   bash scripts/chaos/run_all.sh            all drills (~15 min)
#   bash scripts/chaos/run_all.sh F1 F7      only some
# Drills inject REAL failures (simulator faults, stopped containers, corrupted payloads). Do not run during a demo.
set -u
DIR=$(cd "$(dirname "$0")" && pwd)
export RESULTS=/tmp/fsip-resilience.tsv
: > "$RESULTS"
declare -A DRILLS=([F1]=sim_unavailable [F2]=sim_error_rate [F3]=sim_latency [F4]=sim_stale [F5]=sse_disconnect
                   [F6]=malformed_proxy [F7]=kill_intelligence [F9]=kill_db [F10]=kill_redis [F11]=engine_restart
                   [F15]=sim_reset)
ORDER=(F1 F2 F3 F4 F5 F6 F7 F9 F10 F11 F15)
[ $# -gt 0 ] && ORDER=("$@")
started=$(date -u +%Y-%m-%dT%H:%M:%SZ)
for id in "${ORDER[@]}"; do
  bash "$DIR/${DRILLS[$id]}.sh" || printf '%s\t%s\t-\t-\t-\tFAIL\tdrill aborted (precondition)\n' "$id" "${DRILLS[$id]}" >> "$RESULTS"
done
curl -s -X POST "${SIM:-http://localhost:8000}/admin/faults/clear" >/dev/null

OUT="$DIR/../../docs/evidence/resilience.md"
pass=$(awk -F'\t' '$6=="PASS"' "$RESULTS" | wc -l); total=$(wc -l < "$RESULTS")
{
  echo "# Resilience drills (generated by \`scripts/chaos/run_all.sh\`)"
  echo
  echo "Run started $started against the live stack. Every drill injects a real failure, then measures from"
  echo "\`/api/system/status\` (what the operator sees) how many seconds until the platform **detected** it, checks the"
  echo "automatic mitigation, and how many seconds until it **recovered with no human action**."
  echo
  echo "**Result: $pass / $total drills passed.**"
  echo
  echo "| # | Failure injected | Detected after (s) | Automatic mitigation (measured) | Recovered after (s) | Result | Note |"
  echo "|---|---|---:|---|---:|---|---|"
  awk -F'\t' '{printf "| %s | %s | %s | %s | %s | **%s** | %s |\n", $1, $2, $3, $4, $5, $6, $7}' "$RESULTS"
  echo
  echo "Health is judged from real traffic (breaker state, error ratio and p95 of the last 30 s, the stale header),"
  echo "never from the simulator's \`/v1/health\`, which bypasses fault injection. Incidents with detect / mitigate /"
  echo "recover timestamps: \`GET /api/incidents\` and the System Health page."
} > "$OUT"
echo "== $pass / $total passed → docs/evidence/resilience.md"
