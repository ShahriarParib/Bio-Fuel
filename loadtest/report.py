"""Turn loadtest/out/*.json (k6 summary exports) into docs/evidence/loadtest-report.md."""
from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

OUT = Path("loadtest/out")
REPORT = Path("docs/evidence/loadtest-report.md")
KNEE_MS = 200.0


def load(name: str) -> dict | None:
    p = OUT / name
    return json.loads(p.read_text()) if p.exists() else None


def tb(name: str) -> str:
    p = OUT / name
    return p.read_text().strip() if p.exists() else "n/a"


def row(m: dict) -> tuple[float, float, float, float]:
    d = m["metrics"]["http_req_duration"]
    return d["p(50)"], d["p(95)"], m["metrics"]["http_reqs"]["rate"], m["metrics"]["http_req_failed"]["value"]


def main() -> None:
    levels = sorted({int(p.stem.split("-")[-1]) for p in OUT.glob("read-x1-*.json")})
    lines = ["# Load test (generated by `loadtest/run_loadtest.sh`)", "",
             f"Run {datetime.now(UTC):%Y-%m-%d %H:%M} UTC with k6 0.54 against the live stack through nginx (the same "
             "path a browser uses). Each virtual user behaves like an open console: `/api/state` every second (ETag), "
             "recommendations and alerts every 3 s, system status every 5 s. "
             "The simulator keeps running and the engine "
             "keeps planning during the test.", "",
             "## Read load: api ×1 vs ×3", "",
             "| VUs | x1 p50 ms | x1 p95 ms | x1 req/s | x1 errors | x3 p50 ms | x3 p95 ms | x3 req/s | x3 errors "
             "| engine ticks behind (max) |",
             "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    knee = {1: None, 3: None}
    for v in levels:
        cells = [str(v)]
        for r in (1, 3):
            m = load(f"read-x{r}-{v}.json")
            if m is None:
                cells += ["—"] * 4
                continue
            p50, p95, rps, err = row(m)
            if p95 > KNEE_MS and knee[r] is None:
                knee[r] = v
            cells += [f"{p50:.1f}", f"**{p95:.1f}**" if p95 > KNEE_MS else f"{p95:.1f}", f"{rps:.0f}", f"{err:.2%}"]
        cells.append(f"{tb(f'tb-x1-{v}.txt')} / {tb(f'tb-x3-{v}.txt')}")
        lines.append("| " + " | ".join(cells) + " |")
    lines += ["", "**Knee** (first load level where p95 > 200 ms): "
              f"api ×1: {knee[1] or f'not reached up to {levels[-1]} VUs'}; "
              f"api ×3: {knee[3] or f'not reached up to {levels[-1]} VUs'}.", ""]
    s = load("spike.json")
    if s:
        p50, p95, rps, err = row(s)
        lines += ["## Spike: 10 → 300 VUs in 5 s (api ×3)", "",
                  f"p50 {p50:.1f} ms · p95 {p95:.1f} ms · {rps:.0f} req/s · errors {err:.2%} · "
                  f"engine ticks behind (max) {tb('tb-spike.txt')}", ""]
    codes = OUT / "ratelimit-codes.txt"
    if codes.exists():
        lines += ["## Rate limit (normal configuration: 600 requests/min per client)", "",
                  "700 requests from one client in a row, status codes:", "", "```",
                  codes.read_text().strip(), "```", "", "Response headers once limited:", "", "```",
                  (OUT / "ratelimit-headers.txt").read_text().strip(), "```", ""]
    lines += ["## Why the engine does not notice",
              "The api is stateless and serves the state document the engine publishes to Redis (with a content-hash "
              "ETag, so unchanged content costs a 304). Operator traffic never reaches the engine or the simulator, so "
              "decision freshness (`fsip_ticks_behind`) is independent of API load: a bulkhead by design.", "",
              "Reproduce: `make up && make obs-up && bash loadtest/run_loadtest.sh`."]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {REPORT}")


if __name__ == "__main__":
    main()
